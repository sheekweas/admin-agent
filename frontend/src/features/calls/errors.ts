export function knownVoiceErrorMessage(code: string, language: 'ru' | 'kk' = 'ru') {
  return errors[code]?.[language === 'kk' ? 1 : 0];
}

export function voiceErrorMessage(error: unknown, language: 'ru' | 'kk' = 'ru') {
  const code = typeof error === 'object' && error !== null && 'code' in error ? String(error.code) : '';
  return knownVoiceErrorMessage(code, language) || (error instanceof Error ? error.message : language === 'kk' ? 'Қоңырауды бастау мүмкін болмады.' : 'Не удалось начать звонок.');
}
